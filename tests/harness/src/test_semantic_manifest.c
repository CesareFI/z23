/* The golden vector plus the facts extension and one PROBES record with two
 * UNKNOWN slots: the dump then renders all three composite element shapes
 * (env "T=b:T", layout field "T@q:u:T", probe slot "u:b"). */
static bool smt_dump_manifest(uint8_t **out, size_t *len)
{
    struct vcs_semantic_builder_v1 *b = vcs_semantic_builder_v1_new();
    struct vcs_semantic_record_v1 r = {0};
    struct vcs_semantic_facts_v1 f = {.max_records = 64,
                                      .max_section_bytes = 65536};
    char why[256];
    bool ok = b != NULL && vcs_semantic_builder_v1_enable_facts(b, &f) &&
              smt_golden_identity(b, &r) && smt_golden_function(b, &r) &&
              smt_golden_layout_enum(b, &r) &&
              smt_golden_file(b, &r, "inc/a.h", "#define A_MAX 16\n",
                              VCS_SEMANTIC_ORIGIN_V1_REPO) &&
              smt_golden_file(b, &r, "src/a.c",
                              "#include \"a.h\"\nint f(void) { return A_MAX; }\n",
                              VCS_SEMANTIC_ORIGIN_V1_MAIN) &&
              smt_golden_lookup_macro_decl(b, &r);
    if (ok) {
        vcs_semantic_record_v1_reset(&r);
        vcs_semantic_record_v1_cstr(&r, "src/a.c");
        vcs_semantic_record_v1_cstr(&r, "a.h");
        vcs_semantic_record_v1_u8(&r, VCS_SEMANTIC_FORM_V1_QUOTED);
        vcs_semantic_record_v1_u8(&r, VCS_SEMANTIC_LOOKUP_V1_INCLUDE);
        vcs_semantic_record_v1_u8(&r, 1);
        vcs_semantic_record_v1_u32(&r, 2);
        vcs_semantic_record_v1_u32(&r, 0);
        vcs_semantic_record_v1_u8(&r, VCS_SEMANTIC_PROBE_V1_NO_SNAPSHOT);
        vcs_semantic_record_v1_u32(&r, 3);
        vcs_semantic_record_v1_u8(&r, VCS_SEMANTIC_PROBE_V1_STALE);
        ok = vcs_semantic_builder_v1_add(b, VCS_SEMANTIC_SECTION_V1_PROBES, &r);
    }
    ok = ok && vcs_semantic_builder_v1_finish(b, out, len, why, sizeof(why));
    if (!ok && b != NULL)
        printf("dump manifest refused: %s\n", why);
    vcs_semantic_record_v1_free(&r);
    vcs_semantic_builder_v1_free(b);
    return ok;
}

