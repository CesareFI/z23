/* ── small file helpers ─────────────────────────────────────────────────── */

static bool smt_mkdirs(const char *root, const char *rel)
{
    char path[PATH_MAX];
    int w = snprintf(path, sizeof(path), "%s/%s", root, rel);
    if (w < 0 || (size_t)w >= sizeof(path))
        return false;
    for (char *p = path + strlen(root) + 1; *p != '\0'; p++) {
        if (*p != '/')
            continue;
        *p = '\0';
        if (mkdir(path, 0700) != 0 && errno != EEXIST)
            return false;
        *p = '/';
    }
    return true;
}

static bool smt_write(const char *root, const char *rel, const char *body)
{
    char path[PATH_MAX];
    FILE *fp;
    bool ok;
    if (!smt_mkdirs(root, rel))
        return false;
    (void)snprintf(path, sizeof(path), "%s/%s", root, rel);
    fp = fopen(path, "wb");
    if (fp == NULL)
        return false;
    ok = fwrite(body, 1, strlen(body), fp) == strlen(body);
    return fclose(fp) == 0 && ok;
}

static bool smt_read(const char *path, uint8_t **out, size_t *len)
{
    FILE *fp = fopen(path, "rb");
    long size;
    bool ok = false;
    *out = NULL;
    *len = 0;
    if (fp == NULL)
        return false;
    if (fseek(fp, 0, SEEK_END) == 0 && (size = ftell(fp)) > 0 &&
        fseek(fp, 0, SEEK_SET) == 0) {
        *out = malloc((size_t)size); // raw-alloc-ok:test-fixture-read
        ok = *out != NULL && fread(*out, 1, (size_t)size, fp) == (size_t)size;
        *len = (size_t)size;
    }
    (void)fclose(fp);
    return ok;
}

static bool smt_write_tree(const char *root)
{
    return smt_write(root, "inc/b/shape.h", k_smt_shape_h) &&
           smt_write(root, "inc/a/other.h", k_smt_other_h) &&
           smt_write(root, "src/main.c", k_smt_main_c);
}

/* Replace the first occurrence of `from` with `to` in root/rel. */
static bool smt_edit(const char *root, const char *rel, const char *from,
                     const char *to)
{
    char path[PATH_MAX], out[8192];
    uint8_t *b = NULL;
    size_t n = 0;
    const char *hit;
    bool ok = false;
    (void)snprintf(path, sizeof(path), "%s/%s", root, rel);
    if (!smt_read(path, &b, &n) || n + strlen(to) >= sizeof(out))
        goto done;
    memcpy(out, b, n);
    out[n] = '\0';
    hit = strstr(out, from);
    if (hit != NULL) {
        char tail[8192];
        (void)snprintf(tail, sizeof(tail), "%s", hit + strlen(from));
        (void)snprintf(out + (hit - out), sizeof(out) - (size_t)(hit - out),
                       "%s%s", to, tail);
        ok = smt_write(root, rel, out);
    }
done:
    free(b);
    return ok;
}

/* ── the seeds, applied to a fresh copy of the base tree ─────────────────── */

struct smt_argv {
    const char *items[16];
    size_t n;
    char absolute_include[PATH_MAX + 16];
};

static void smt_base_argv(struct smt_argv *a, const char *root)
{
    (void)snprintf(a->absolute_include, sizeof(a->absolute_include),
                   "-I%s/inc/c", root);
    const char *base[] = {"-std=c23", "-O2", "-Iinc/a", "-Iinc/b",
                          a->absolute_include, "-DFOO=1", "-Wall"};
    a->n = sizeof(base) / sizeof(base[0]);
    for (size_t k = 0; k < a->n; k++)
        a->items[k] = base[k];
}

static bool smt_apply_argv(enum smt_seed_id id, struct smt_argv *a)
{
    const char *t;
    switch (id) {
    case SMT_FLAG_DEFINE:
        a->items[a->n++] = "-DEXTRA=1";
        return true;
    case SMT_FLAG_OPT:
        a->items[1] = "-O0";
        return true;
    case SMT_FLAG_REORDER:
        t = a->items[0];
        a->items[0] = a->items[1];
        a->items[1] = t;
        return true;
    default:
        return true;
    }
}

static bool smt_apply_files(enum smt_seed_id id, const char *root)
{
    switch (id) {
    case SMT_HEADER_DECL:
        return smt_edit(root, "inc/b/shape.h", "#endif\n",
                        "int shape_extra(void);\n#endif\n");
    case SMT_MACRO_BODY:
        return smt_edit(root, "inc/b/shape.h", "SHAPE_MAX 16", "SHAPE_MAX 17");
    case SMT_LAYOUT_ADD:
        return smt_edit(root, "inc/b/shape.h", "    unsigned flag : 3;\n",
                        "    unsigned flag : 3;\n    int extra;\n");
    case SMT_LAYOUT_REORDER:
        return smt_edit(root, "inc/b/shape.h",
                        "    int kind;\n    shape_dim dim;\n",
                        "    shape_dim dim;\n    int kind;\n");
    case SMT_SHADOW:
        return smt_write(root, "inc/a/shape.h", k_smt_shape_h);
    case SMT_FN_BODY:
        return smt_edit(root, "src/main.c", "+ SHAPE_MAX", "- SHAPE_MAX");
    case SMT_COMMENT:
        /* Outside AND inside function bodies: libclang's tokenizer keeps
         * comments as tokens, so only the inside edit proves they are
         * dropped from the function token hash. */
        return smt_edit(root, "src/main.c", "static int helper",
                        "/* only a comment moves */\nstatic int helper") &&
               smt_edit(root, "src/main.c", "{ return SHAPE_SCALE",
                        "{ /* inside */ return SHAPE_SCALE") &&
               smt_edit(root, "inc/b/shape.h", "SHAPE_MAX 16",
                        "SHAPE_MAX /* in a macro body */ 16");
    default:
        return true;
    }
}

/* ── expectations shared by both groups ─────────────────────────────────── */

struct smt_fn_seen {
    char name[64];
    uint32_t count;
};

static void smt_fn_cb(void *ctx, enum vcs_semantic_fn_change_v1 change,
                      const char *path, size_t path_len, const char *name,
                      size_t name_len)
{
    struct smt_fn_seen *seen = ctx;
    (void)change;
    (void)path;
    (void)path_len;
    if (seen->count++ == 0 && name_len < sizeof(seen->name)) {
        memcpy(seen->name, name, name_len);
        seen->name[name_len] = '\0';
    }
}

/* 0 when the changed-function report of a diff matches the seed's contract. */
static int smt_check_seed_functions(const struct smt_seed *s,
                                    const struct vcs_semantic_diff_v1 *d,
                                    const struct smt_fn_seen *seen)
{
    if (s->fn_name != NULL &&
        (d->functions_changed != s->fn_changed || strcmp(seen->name, s->fn_name) != 0)) {
        printf("FAIL seed %s: changed functions %u (first %s)\n", s->name,
               d->functions_changed, seen->name);
        return 1;
    }
    if (s->fn_name == NULL && (s->sections & SMT_BIT(FUNCTIONS)) == 0 &&
        seen->count != 0) {
        printf("FAIL seed %s: %u function(s) moved\n", s->name, seen->count);
        return 1;
    }
    return 0;
}

/* 0 when the base->seed pair meets the seed's contract; prints why not. */
static int smt_check_seed(const struct smt_seed *s, const uint8_t *base,
                          size_t base_len, const uint8_t *m, size_t m_len)
{
    struct vcs_semantic_diff_v1 d;
    struct smt_fn_seen seen = {0};
    uint8_t r0[32], r1[32], h0[32], h1[32];
    char why[256];
    if (!vcs_semantic_root_v1(base, base_len, r0, why, sizeof(why)) ||
        !vcs_semantic_root_v1(m, m_len, r1, why, sizeof(why)) ||
        !vcs_semantic_hint_root_v1(base, base_len, h0, why, sizeof(why)) ||
        !vcs_semantic_hint_root_v1(m, m_len, h1, why, sizeof(why)) ||
        !vcs_semantic_manifest_v1_diff(base, base_len, m, m_len, &d, smt_fn_cb, &seen)) {
        printf("FAIL seed %s: invalid manifest: %s\n", s->name, why);
        return 1;
    }
    if (memcmp(r0, r1, 32) == 0 || d.exact_equal) {
        printf("FAIL seed %s: exact root did not change\n", s->name);
        return 1;
    }
    if ((memcmp(h0, h1, 32) == 0) != s->hint_equal || d.hint_equal != s->hint_equal) {
        printf("FAIL seed %s: hint root %s\n", s->name,
               s->hint_equal ? "changed" : "did not change");
        return 1;
    }
    if (d.changed_sections != s->sections) {
        printf("FAIL seed %s: changed sections 0x%x, expected 0x%x\n", s->name,
               d.changed_sections, s->sections);
        return 1;
    }
    return smt_check_seed_functions(s, &d, &seen);
}

