enum smt_seed_id {
    SMT_HEADER_DECL, SMT_FLAG_DEFINE, SMT_FLAG_OPT, SMT_FLAG_REORDER,
    SMT_MACRO_BODY, SMT_LAYOUT_ADD, SMT_LAYOUT_REORDER, SMT_SHADOW,
    SMT_FN_BODY, SMT_COMMENT, SMT_SEED_COUNT
};

struct smt_seed {
    const char *name;
    uint32_t sections; /* exactly the sections that must change */
    bool hint_equal;
    uint32_t fn_changed;
    const char *fn_name; /* the one changed function, when fn_changed == 1 */
};

