#include "zcl_wallet.h"

#include <string.h>

/* Pinned zclassicd chainparams.cpp; displayed big-endian hash bytes. */
static const uint8_t main_genesis[32] = {0x00, 0x07, 0x10, 0x4c, 0xcd, 0xa2, 0x89, 0x42, 0x79, 0x19, 0xef, 0xc3, 0x9d, 0xc9, 0xe4, 0xd4, 0x99, 0x80, 0x4b, 0x7b, 0xeb, 0xc2, 0x2d, 0xf5, 0x5f, 0x8b, 0x83, 0x43, 0x01, 0x26, 0x06, 0x02};
static const uint8_t test_genesis[32] = {0x03, 0xe1, 0xc4, 0xbb, 0x70, 0x5c, 0x87, 0x1b, 0xf9, 0xbf, 0xda, 0x3e, 0x74, 0xb7, 0xf8, 0xf8, 0x6b, 0xff, 0x26, 0x79, 0x93, 0xc2, 0x15, 0xa8, 0x9d, 0x57, 0x95, 0xe3, 0x70, 0x8e, 0x5e, 0x1f};

zcl_status zcl_network_genesis(zcl_network network, uint8_t *hash, size_t capacity)
{
    if (hash == NULL)
        return ZCL_INVALID_ARGUMENT;
    if (capacity < 32)
        return ZCL_BUFFER_TOO_SMALL;
    if (network != ZCL_MAINNET && network != ZCL_TESTNET)
        return ZCL_UNSUPPORTED;
    memcpy(hash, network == ZCL_MAINNET ? main_genesis : test_genesis, 32);
    return ZCL_OK;
}
